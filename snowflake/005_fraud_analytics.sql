-- 5. High-risk transactions

CREATE OR REPLACE VIEW HIGH_RISK_TRANSACTIONS AS
SELECT
    TRANSACTION_ID,
    CUSTOMER_ID,
    MERCHANT_ID,
    TRANSACTION_TIMESTAMP,
    AMOUNT,
    CURRENCY,
    CITY,
    RISK_SCORE,
    RISK_LEVEL,
    FRAUD_REASONS,
    IS_SUSPICIOUS

FROM FACT_TRANSACTIONS

WHERE RISK_LEVEL = 'HIGH'

ORDER BY
    RISK_SCORE DESC,
    TRANSACTION_TIMESTAMP DESC;
